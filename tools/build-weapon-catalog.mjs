// Keep server equipment numbers identical to src/data/weapons.ts.
import fs from 'node:fs';
import { createServer } from 'vite';
const server = await createServer({ configFile: false, logLevel: 'error', server: { middlewareMode: true } });
let WEAPONS, ITEMS, VENDOR_STOCK, DEFAULT_STACK, FOOD_EFFECTS, ORIGINAL_WEAPONS, OUTFITS, EQUIPPABLE;
try {
  ({ WEAPONS } = await server.ssrLoadModule('/src/data/weapons.ts'));
  ({ OUTFITS } = await server.ssrLoadModule('/src/data/outfits.ts'));
  ({ EQUIPPABLE } = await server.ssrLoadModule('/src/data/equipment.ts'));
  ({ ITEMS, VENDOR_STOCK, DEFAULT_STACK } = await server.ssrLoadModule('/src/data/items.ts'));
  ({ FOOD_EFFECTS } = await server.ssrLoadModule('/src/data/food.ts'));
  ({ ORIGINAL_WEAPONS } = await server.ssrLoadModule('/src/data/uniqueWeapons.ts'));
} finally { await server.close(); }
const rows = Object.entries(EQUIPPABLE).map(([id, w]) => {
 const meta=Object.fromEntries(['cls','slot','tier','kind','guard','power','healing','maxHealth','maxResource'].filter(key=>w[key]!==undefined).map(key=>[key,w[key]]));
 return `    when '${id}' then '${JSON.stringify(meta)}'::jsonb`;
}).join('\n');
fs.writeFileSync(new URL('../supabase/server/05-weapon-stats.sql', import.meta.url), `-- Generated by tools/build-weapon-catalog.mjs from src/data/weapons.ts.\ncreate or replace function public.game_equipment_item(p_item text)
returns jsonb language sql immutable set search_path='' as $$
  select case p_item
${rows}
    else null
  end
$$;

-- Only class-compatible equipment in its declared slot contributes stats.
create or replace function public.game_equipment_stat(d jsonb, p_stat text)
returns int language sql immutable set search_path='' as $$
  select coalesce(sum(coalesce((meta->>p_stat)::int,0)),0)::int
  from (select public.game_equipment_item(d->'equipment'->slot->>'id') as meta, slot
    from (values ('head'),('pendant'),('chest'),('hands'),('ring'),('weapon'),('offhand'),('legs'),('feet'),('trinket')) as slots(slot)
    where d->'equipment'->slot->>'count'='1') as equipped
  where (meta->>'cls' is null or meta->>'cls'=d->>'cls') and meta->>'slot'=slot
$$;
revoke all on function public.game_equipment_item(text), public.game_equipment_stat(jsonb,text) from public,anon,authenticated;
`);
console.log(`Updated equipment catalog (${Object.keys(WEAPONS).length} weapons, ${Object.keys(OUTFITS).length} outfits).`);

const literal = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
const itemRows = Object.values(ITEMS).map(item => {
  const metadata = { value: item.value, stack: item.stack ?? DEFAULT_STACK, bound: !!item.bound,
    sellable: item.sellable !== false, rarity: item.rarity };
  if (item.food) metadata.food_seconds = FOOD_EFFECTS[item.food].duration;
  if (item.restore?.kind === 'health') metadata.heal_pct = item.restore.percent;
  else if (item.restore) { metadata.resource_pct = item.restore.percent; metadata.resource_kind = item.restore.kind; }
  return `    when '${item.id}' then ${literal(metadata)}`;
}).join('\n');
const vendorRows = Object.entries(VENDOR_STOCK).map(([vendor, items]) =>
  `    when '${vendor}' then array[${items.map(id => `'${id}'`).join(',')}]`).join('\n');
fs.appendFileSync(new URL('../supabase/server/05-weapon-stats.sql', import.meta.url), `
-- Catalog and rarity metadata share the same source as the client, including existing consumables.
create or replace function public.game_item(p_item text)
returns jsonb language sql immutable set search_path='' as $$
  select case p_item
${itemRows}
    else null
  end
$$;

create or replace function public.game_vendor_stock(p_vendor text)
returns text[] language sql immutable set search_path='' as $$
  select case p_vendor
${vendorRows}
    else array[]::text[]
  end
$$;
`);
console.log(`Updated item metadata, rarities and stock (${Object.keys(ITEMS).length} items).`);

const itemRoot = new URL('../src/assets/models/items/', import.meta.url);
const modelFiles = new Map();
function collect(folder, prefix = '') {
  for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
    if (entry.isDirectory()) collect(new URL(`${entry.name}/`, folder), `${prefix}${entry.name}/`);
    else if (entry.name.endsWith('.glb')) modelFiles.set(entry.name.slice(0, -4), `${prefix}${entry.name}`);
  }
}
collect(itemRoot);
const manifest = Object.entries(WEAPONS).map(([id, weapon]) => {
  const original = ORIGINAL_WEAPONS.find(item => item.id === id);
  return { id, label: ITEMS[id].label, ...weapon, collection: original?.collection,
    model: modelFiles.get(id) ?? (original ? `collections/${original.collection}/${id}.glb` : `tier${weapon.tier}/${id}.glb`) };
});
fs.writeFileSync(new URL('weapon_manifest.json', itemRoot), `${JSON.stringify(manifest, null, 2)}\n`);
const equipmentManifest=Object.entries(EQUIPPABLE).map(([id,meta])=>({id,label:ITEMS[id].label,...meta,
 model:WEAPONS[id]?`items/${modelFiles.get(id)}`:id.startsWith('traje_')?`wardrobe/classes/modular/${id}.glb`:`items/accessories/${id}.glb`,
}));
fs.writeFileSync(new URL('equipment_manifest.json',itemRoot),JSON.stringify(equipmentManifest,null,2)+'\n');
